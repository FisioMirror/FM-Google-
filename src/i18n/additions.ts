/** Fusión profunda de un bundle extra sobre un diccionario base. */
export function withAdditions<T extends Record<string, any>>(base: T, extra: Record<string, Section>): T {
  const out: Record<string, any> = { ...base };
  for (const [section, values] of Object.entries(extra)) {
    out[section] = { ...(out[section] || {}), ...values };
  }
  return out as T;
}
